#!/usr/bin/env python3
"""The station's route for WhatsApp calls, made from the line's own route.

WhatsApp calls reach Zeytun's station through LeadDrive's relay
(wa-sip.leaddrivecrm.org, owner 2026-11-12) and take the same path as the
operator DID: the same AGI, AI leg, transfer and recording. One thing differs:
the WhatsApp app cancels its own echo, so the voice core must not drop the
caller's speech while the agent talks. The core learns that from a mark the AI
leg leaves before it connects (zeytun_whatsapp_call). The shared route
(fanum-inbound-browser.conf) is pinned line by line by its installer, so the
WhatsApp route is a renamed copy of it with that one line added; run this
again whenever the shared route changes (a test compares the two).

Usage: make-wa-dialplan.py <fanum-inbound-browser.conf>  > dialplan-wa-relay.conf
"""
import sys

MARKS = "/run/fanum-whatsapp-calls"
LINE_DID = "994995111103"


def section(text: str, name: str) -> str:
    start = text.index(f"[{name}]\n")
    end = text.find("\n[", start + 1)
    return text[start:] if end < 0 else text[start:end + 1]


def make(shared: str) -> str:
    browser = section(shared, "fanum-inbound-browser").replace("[fanum-inbound-browser]", "[fanum-wa-inbound]", 1)
    leg = section(shared, "fanum-inbound-ai-leg").replace("[fanum-inbound-ai-leg]", "[fanum-wa-ai-leg]", 1)
    if browser.count("Local/s@fanum-inbound-ai-leg/n") != 1 or leg.count(" same => n,AudioSocket(") != 1:
        raise SystemExit("shared route changed shape: review make-wa-dialplan.py")
    browser = browser.replace("Local/s@fanum-inbound-ai-leg/n", "Local/s@fanum-wa-ai-leg/n")
    leg = leg.replace(" same => n,AudioSocket(",
                      f" same => n,System(/usr/bin/touch {MARKS}/${{FANUM_SAFE_CALL_ID}})\n same => n,AudioSocket(", 1)
    return f"""; Generated by scripts/pbx/wa-relay/make-wa-dialplan.py from fanum-inbound-browser.conf.
; WhatsApp calls through LeadDrive's relay: the caller is the pharmacy's WhatsApp
; number, the call takes the line's route under the operator DID {LINE_DID}
; (AI, transfer to a manager, recording, order). Only the relay sends calls here.
[from-wa-relay]
exten => _X.,1,NoOp(Fanum WhatsApp inbound: ${{CALLERID(all)}} to WhatsApp ${{EXTEN}})
 same => n,Set(CHANNEL(language)=az)
 same => n,Set(CALLERID(dnid)={LINE_DID})
 same => n,Set(__FANUM_WHATSAPP_NUMBER=${{EXTEN}})
 same => n,Gosub(fanum-wa-inbound,s,1(fanum-inbound-browser))
 same => n,Hangup()

{browser.rstrip()}

{leg.rstrip()}
"""


if __name__ == "__main__":
    sys.stdout.write(make(open(sys.argv[1], encoding="utf-8").read()))
