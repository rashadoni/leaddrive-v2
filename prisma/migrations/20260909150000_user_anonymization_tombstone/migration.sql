-- Надгробие вместо удаления пользователя.
--
-- Проблема. `prisma.user.delete()` на проде отдавал «Internal server error»
-- для любого сотрудника, который хоть раз что-то делал в журналируемых
-- разделах. Причина — противоречие двух правил, каждое из которых по
-- отдельности разумно:
--
--   • четыре таблицы объявлены «только добавление» и триггером отвергают
--     ЛЮБОЙ UPDATE: forecast_snapshots, compliance_audit_log,
--     entitlement_audit_events, pipeline_stage_transitions;
--   • ссылки на пользователя в них объявлены `onDelete: SetNull`, то есть
--     удаление ОБЯЗАНО их обновить.
--
-- Наблюдалось как PostgresError 23514
-- «forecast_snapshots is append-only (snapshot ... cannot be updated)».
--
-- Решение. Не удалять строку вовсе. Тогда обновлять append-only таблицы не
-- нужно, исключение в триггерах не требуется, и атрибуция в журналах —
-- то, ради чего они и ведутся — сохраняется полностью.
--
-- Это ЕДИНСТВЕННАЯ причина, по которой поле добавляется. Не переиспользовать
-- его как «мягкое удаление вообще»: `isActive: false` уже значит «отключён и
-- может вернуться», а `anonymizedAt` значит «данные стёрты, возврата нет».
ALTER TABLE "users" ADD COLUMN "anonymizedAt" TIMESTAMP(3);

-- Индекс не добавляется намеренно. Список сотрудников фильтрует
-- `anonymizedAt IS NULL`, а этому условию удовлетворяют почти все строки:
-- обезличенные — редкое исключение. Индекс по признаку, который у
-- подавляющего большинства строк одинаков, планировщик всё равно не выберет,
-- и существующий индекс по `organizationId` отработает лучше.
