/**
 * Пост-соболезнование: печальный тон без претензии к бренду.
 *
 * Зачем понадобилось. Правило «родительский пост негативный → берём под ним ВСЕ
 * комментарии» держится на метке тональности поста. Метку ставит лексика, а
 * лексика не отличает горе от жалобы: видео «Araz Market продолжает платить
 * зарплату сыну шехида» — хорошая для бренда история — получило negative по
 * словам «şəhid», «Allah rəhmət eləsin» и по плачущим смайликам. После этого
 * 275 соболезнований под ним стали принятыми находками: 246 разных авторов,
 * ни одного слова про магазин.
 *
 * Замер на проде (2026-08-03, 13 постов, 413 наследованных находок) сравнил два
 * гейта:
 *
 * - «требовать в посте признак претензии» — сработал на 7 из 13 и снёс бы
 *   наследование у шести настоящих жалоб (нет свежего хлеба, антимонопольное
 *   дело по «Veysəloğlu», экспертиза аптек «Zeytun»): −31 законная находка;
 * - «исключить соболезнования» — сработал ровно на одном посте, том самом,
 *   и ни на одной настоящей жалобе: −275 шума, законные не тронуты.
 *
 * Поэтому гейт отрицательный: мы не требуем от поста доказательств претензии,
 * мы снимаем с него право раздавать релевантность, когда его негатив — это
 * траур. Сам пост при этом остаётся находкой: он упоминает бренд.
 *
 * Комментарии под таким постом не пропадают — они проходят обычную проверку по
 * собственному тексту: упомянул алиас или пожаловался — попал в находки.
 */

/**
 * Азербайджанские буквы к ASCII.
 *
 * Диакритику в комментариях ставят как попало: «şəhid», «sehid», «Şehidim»,
 * «məkanı», «mekanin». Прод 2026-08-04 показал цену перечисления написаний —
 * «Mekanin cennet olsun Şehidim. Halaldı sənə Araz market» не поймалось ни одним
 * из вариантов и ушло в ленту как негатив. Поэтому текст сводится к ASCII, а
 * формулы пишутся один раз.
 */
const AZ_FOLD: Record<string, string> = {
  "ə": "e", "ş": "s", "ç": "c", "ğ": "g", "ı": "i", "ö": "o", "ü": "u", "İ": "i",
}

function foldAzerbaijani(value: string): string {
  return value
    .toLowerCase()
    .replace(/\u0307/g, "")
    .replace(/[əşçğıöüİ]/g, letter => AZ_FOLD[letter] ?? letter)
}

/**
 * Формулы соболезнования и памяти о погибших — на сложённом ASCII, поэтому
 * покрывают любое написание диакритики. Азербайджанский, турецкий, русский,
 * английский.
 */
const CONDOLENCE_PATTERNS: RegExp[] = [
  // «Да помилует Аллах» — ядро азербайджанского соболезнования.
  /\brehmet\s+(?:ele|eyle|et)/iu,
  /\ballah\s+rehmet\b/iu,
  // «Шехид» — павший; в постах-данях встречается и как слово, и как хештег.
  /(?:^|[^\p{L}])#?sehid/iu,
  /(?:^|[^\p{L}])#?shehid/iu,
  // Кириллица без \b: в JS граница слова считается по ASCII, поэтому перед «ш»
  // её нет и /\bшехид/ не срабатывает вовсе.
  /(?:^|[^\p{L}])шехид/iu,
  // «Пусть его место будет раем» — с любым притяжательным окончанием
  // («məkanı», «məkanın», «mekanin»), которых на проде встречается сразу три.
  /\bmekan(?:i|in|nin)?\s+cennet/iu,
  // «Да успокоится душа».
  /\bruhu?n?\s+sad\s+olsun/iu,
  // Смерть и соболезнование прямым словом.
  /\bvefat\s+(?:etdi|etti|edib)/iu,
  /\bbasiniz\s+sag\s+olsun/iu,
  /(?:^|[^\p{L}])соболезнован/iu,
  /(?:^|[^\p{L}])светлая\s+память/iu,
  /(?:^|[^\p{L}])покойся\s+с\s+миром/iu,
  /\bcondolence/iu,
  /\brest\s+in\s+peace\b/iu,
  /\brip\b(?=\s|$)/iu,
]

/**
 * Текст оплакивает человека, а не предъявляет что-то бренду.
 *
 * Два применения: снять с родительского поста право раздавать релевантность всем
 * комментариям и не считать соболезнование негативом при разборе комментария.
 * Признак претензии в обоих случаях проверяется РАНЬШЕ — жалоба в траурной ветке
 * остаётся жалобой.
 */
export function isCondolencePost(text: string | null | undefined): boolean {
  const value = foldAzerbaijani(String(text ?? "").trim())
  if (!value) return false
  return CONDOLENCE_PATTERNS.some(pattern => pattern.test(value))
}
