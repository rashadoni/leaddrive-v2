/**
 * Аптека заказа, которую назвали только словами, — не аптека заказа, пока её
 * не подтвердил менеджер.
 *
 * Звонящий с любого номера говорит «я из 92 Yasamal», линия находит эту аптеку
 * в 1С по словам (`named_matched`), и заказ привязывается к её настоящему
 * контрагенту. До 2026-11-11 пометка «проверьте» была только цветом на
 * карточке: «Подтвердить» отправлял в 1С документ на чужую аптеку, а
 * подтверждённый заказ становился её историей, которую линия потом читает её
 * настоящим звонящим. Решает теперь код: такой заказ не подтверждается (ни
 * кнопкой, ни голосом, ни в 1С), пока менеджер не подтвердит аптеку — тогда
 * она становится `manager_selected`, как выбранная им вручную.
 *
 * Номер звонящего (`phone_unique`, `phone_shared`) — это всё ещё то, что
 * знает 1С про эту аптеку, а не слова звонящего, и проверки не требует.
 */
export const PHARMACY_IDENTIFICATIONS_TO_CHECK: ReadonlySet<string> = new Set(["named_matched"])

export function pharmacyNeedsManagerCheck(identification: string | null | undefined): boolean {
  return !!identification && PHARMACY_IDENTIFICATIONS_TO_CHECK.has(identification)
}
