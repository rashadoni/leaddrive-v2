import type { Prisma } from "@prisma/client"

/**
 * Надгробие вместо удаления пользователя.
 *
 * Физически удалить пользователя нельзя: на него ссылаются четыре таблицы под
 * триггером «только добавление» — `forecast_snapshots`,
 * `compliance_audit_log`, `entitlement_audit_events`,
 * `pipeline_stage_transitions`. Их связи объявлены `onDelete: SetNull`, то есть
 * удаление обязано их ОБНОВИТЬ, а триггер любой UPDATE отвергает. На проде это
 * выглядело как «Internal server error» и Postgres 23514.
 *
 * Обходить триггер исключением было бы хуже: в журналах соответствия ценно
 * именно «кто это сделал», ради этого они и ведутся. Обнулив автора, мы бы
 * сохранили таблицу и потеряли её смысл.
 *
 * Поэтому строка остаётся, `id` живёт, а персональные данные затираются.
 *
 * ВАЖНО про честность формулировок: это ПСЕВДОНИМИЗАЦИЯ, а не необратимая
 * анонимность. `id` сохраняется, и если он сопоставим с человеком через другую
 * систему, связь восстановима. Для журналов соответствия это ровно то, что
 * нужно; если когда-нибудь потребуется необратимость, придётся отдельно решать
 * судьбу самого идентификатора — не выдавать это за уже сделанное.
 */

/** Заглушка имени. Не пустая строка: `name` в схеме обязательный, а пустое имя в списках выглядит как сбой отрисовки. */
export const ANONYMIZED_USER_NAME = "Удалённый пользователь"

/**
 * Домен для затёртой почты. `.invalid` зарезервирован RFC 2606 именно под это:
 * он гарантированно не резолвится, поэтому такой адрес нельзя случайно
 * использовать для отправки письма.
 */
const ANONYMIZED_EMAIL_DOMAIN = "invalid.local"

/**
 * Почту нельзя просто очистить: на неё стоит `@@unique([organizationId, email])`,
 * и вторая же пустая строка в организации упёрлась бы в конфликт. Поэтому
 * заглушка уникальна по `id` — он и так остаётся в строке.
 */
export function anonymizedEmailFor(userId: string): string {
  return `deleted-${userId}@${ANONYMIZED_EMAIL_DOMAIN}`
}

/**
 * Пароль, которым нельзя войти. Не пустая строка и не валидный bcrypt-хеш:
 * так проверка пароля не совпадёт ни с чем и не упадёт с исключением на
 * разборе формата.
 */
const UNUSABLE_PASSWORD_HASH = "!anonymized:no-login"

/**
 * Данные для затирания. Отдельной функцией, а не инлайном в роуте, чтобы
 * список полей был в одном месте: пропущенное поле здесь — это утечка
 * персональных данных, которую тест сможет поймать только зная, где искать.
 */
export function buildUserAnonymizationData(userId: string, now: Date = new Date()): Prisma.UserUpdateInput {
  return {
    // Персональные данные — затираем.
    name: ANONYMIZED_USER_NAME,
    email: anonymizedEmailFor(userId),
    phone: null,
    verifiedPhone: null,
    avatar: null,
    department: null,

    // Доступ — закрываем. `isActive: false` уже отвергается и при проверке
    // пароля (`auth-credentials.ts`), и при обновлении сессии (`auth.ts`).
    isActive: false,
    passwordHash: UNUSABLE_PASSWORD_HASH,

    // Секреты второго фактора — не оставляем, они тоже персональные данные
    // и с ними обезличенная строка остаётся пригодной для входа.
    totpSecret: null,
    totpEnabled: false,
    smsAuthEnabled: false,
    require2fa: false,
    backupCodes: [],
    twoFactorNonce: null,

    // Токены восстановления и календаря — иначе по старой ссылке можно
    // дотянуться до затёртой учётки.
    resetToken: null,
    resetTokenExp: null,
    calendarToken: null,

    // Сдвиг `passwordChangedAt` инвалидирует живые сессии: их проверка
    // сравнивает метку в токене с этим полем.
    passwordChangedAt: now,

    // Собственно надгробие. Отличает «стёрт» от «отключён»: `isActive: false`
    // обратим, `anonymizedAt` — нет.
    anonymizedAt: now,
  }
}
